/// One claim element in the shape the store answers, tagged by `kind`
/// (contract on carrick#1564, comment 5937606126, sections 2 and 3, as
/// amendment 2, comment 5939543981, changes them). A maker's parts are
/// slots. An op, scope or reserved name carries `on` or `of`, never both
/// (the verifier answers `claim_invalid`): `of` is the one receiver it
/// applies to, by its receiver id. `picker` and `name_scope` travel with the
/// claim and are never read by the verifier.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum LibraryClaim {
    /// `member(...)` or `new member(...)` makes an instance; `member: None`
    /// is the export itself. A definition is a maker with a `name` and a
    /// `handler` slot; a queue (`new Queue("emails")`) one with a
    /// positional `name`.
    Make {
        form: MakeForm,
        member: Option<String>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        base: Option<ClaimSlot>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        prefix: Option<ClaimSlot>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        name: Option<ClaimSlot>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        handler: Option<ClaimSlot>,
        /// Label v2: the function or client the maker runs (a hook runs the
        /// query function it is given).
        #[serde(default, skip_serializing_if = "Option::is_none")]
        runs: Option<ClaimSlot>,
        #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
        key_labels: BTreeMap<String, KeyLabel>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        name_scope: Option<NameScope>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        picker: Option<String>,
    },
    /// `member(name)` (after `path`) returns a receiver bound to that name.
    /// A procedure router's member (`collects`, #2474 R6a) has no name: a
    /// scope carries exactly one of `name` and `collects`, and the store
    /// reader drops one with neither.
    Scope {
        member: String,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        name: Option<ClaimSlot>,
        #[serde(default, skip_serializing_if = "Vec::is_empty")]
        path: Vec<String>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        on: Option<ClaimOn>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        of: Option<String>,
        #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
        key_labels: BTreeMap<String, KeyLabel>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        name_scope: Option<NameScope>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        picker: Option<String>,
        /// Route fields (#2474 R0): the member runs the function here and
        /// hands it, as `yields` says, an instance bound under `name`.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        runs: Option<ClaimSlot>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        yields: Option<Box<Yields>>,
        /// Route fields (#2474 R0): the instance handed here is served under
        /// `name`.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        mounts: Option<ClaimSlot>,
        /// Procedure routers (#2474 R6a): the member collects procedures by
        /// key and returns the collection.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        collects: Option<Collects>,
    },
    /// A member that acts on the wire; `member: None` is the object `path`
    /// reaches (the receiver itself when `path` is empty).
    Op {
        op: LibraryOp,
        member: Option<String>,
        /// The members walked from the receiver to the object `member` sits
        /// on (`client.tasks.trigger`).
        #[serde(default, skip_serializing_if = "Vec::is_empty")]
        path: Vec<String>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        on: Option<ClaimOn>,
        /// The one receiver the op acts on, by its receiver id
        /// (`instance:new`, `instance:connect>scope:channel`).
        #[serde(default, skip_serializing_if = "Option::is_none")]
        of: Option<String>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        name: Option<OpName>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        payload: Option<ClaimSlot>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        handler: Option<ClaimSlot>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        ack: Option<ClaimSlot>,
        #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
        key_labels: BTreeMap<String, KeyLabel>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        name_scope: Option<NameScope>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        picker: Option<String>,
        /// HTTP: an options object sits at this argument (no key).
        #[serde(default, skip_serializing_if = "Option::is_none")]
        options: Option<ClaimSlot>,
        /// HTTP: the method the member always sends.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        method: Option<String>,
        /// HTTP: where the method sits.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        method_key: Option<ClaimSlot>,
        /// HTTP (label v2): the method sent when the call names none. Beside
        /// `method_key`, the default when that option is absent; alone, the
        /// one method the call sends whatever its member is called.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        method_default: Option<String>,
        /// HTTP (label v2): where the base URL the path joins sits.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        base: Option<ClaimSlot>,
        /// Label v2: the function or client the op runs. Boxed, as is
        /// `yields`, so an op stays near the size of the other claims.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        runs: Option<Box<RunsSlot>>,
        /// Label v2, `receive` only: what the handler is handed.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        yields: Option<Box<Yields>>,
        /// Route fields (#2474 R0), `receive` only: where the handler's
        /// request holds its path and method.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        request: Option<Box<RequestAt>>,
    },
    /// A name the library emits itself, spelled in one of `member`'s
    /// parameters.
    Reserved {
        member: String,
        name: String,
        #[serde(default, skip_serializing_if = "Vec::is_empty")]
        path: Vec<String>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        on: Option<ClaimOn>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        of: Option<String>,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        picker: Option<String>,
    },
}

