/// How an anchor was produced upstream (design-doc amendment 2). Mirrors the
/// sidecar's `AnchorOrigin` (src/sidecar/src/capture/api.ts).
#[derive(Debug, Clone, Copy, Serialize, Deserialize, PartialEq, Eq)]
pub enum AnchorOrigin {
    #[serde(rename = "llm-symbol")]
    LlmSymbol,
    #[serde(rename = "deterministic-infer")]
    DeterministicInfer,
    #[serde(rename = "anchor-backfill")]
    AnchorBackfill,
    /// No type request reached capture for a manifest alias, so the driver
    /// sends an `unknown` placeholder rather than letting the surface omit it
    /// (cloud#1184).
    #[serde(rename = "manifest-placeholder")]
    ManifestPlaceholder,
}

/// One anchor for the `capture_v2` action. Mirrors the sidecar's
/// `CaptureAnchorRequest` union — the stdio action surface is the only
/// contract Rust sees (seam, not split).
#[derive(Debug, Clone, Serialize, PartialEq)]
#[serde(tag = "kind", rename_all = "snake_case")]
pub enum CaptureAnchor {
    /// Explicit exported symbol: `export type A = import('./m').Sym;`
    Symbol {
        alias: String,
        symbol_name: String,
        source_file: String,
        anchor_origin: AnchorOrigin,
        /// Use-site `[]` levels around the element symbol (#248/#306).
        #[serde(skip_serializing_if = "Option::is_none")]
        array_depth: Option<u32>,
        /// Carried from [`SymbolRequest::consumer_response`] (carrick#1841).
        #[serde(skip_serializing_if = "std::ops::Not::not")]
        consumer_response: bool,
        /// carrick#2814: the symbol is a request body or payload whose
        /// handler works when none is sent, marked by the inference for the
        /// alias. The capture copies it onto the alias's record.
        #[serde(skip_serializing_if = "std::ops::Not::not")]
        absent_body_tolerated: bool,
    },
    /// Addressable handler: `Awaited<ReturnType<typeof import('./m').fn>>`.
    HandlerReturn {
        alias: String,
        symbol_name: String,
        source_file: String,
        anchor_origin: AnchorOrigin,
    },
    /// Anonymous inferred type at a source location (span / text / line).
    Infer {
        alias: String,
        source_file: String,
        anchor_origin: AnchorOrigin,
        #[serde(skip_serializing_if = "Option::is_none")]
        span_start: Option<u32>,
        #[serde(skip_serializing_if = "Option::is_none")]
        span_end: Option<u32>,
        #[serde(skip_serializing_if = "Option::is_none")]
        line_number: Option<u32>,
        #[serde(skip_serializing_if = "Option::is_none")]
        expression_text: Option<String>,
        /// #498: the anchor names a handler PARAMETER, not an expression —
        /// the `InferKind::FunctionParam` locator carried through to capture.
        /// A subscriber's contract is what its handler receives, and without
        /// this the line-only locator resolves the registration CALL and
        /// captures that call's return type instead.
        #[serde(skip_serializing_if = "Option::is_none")]
        param_name: Option<String>,
        /// carrick#2818: the library store's label for the call this anchor
        /// locates; the capture reads the labelled part of the call's result.
        #[serde(default, skip_serializing_if = "Option::is_none")]
        result: Option<ResultShape>,
    },
    /// Inline literal type text (the v1 inline-alias path).
    Literal {
        alias: String,
        type_text: String,
        anchor_origin: AnchorOrigin,
        /// The file the text was printed from, when there is one (a v1
        /// inference result, or a backfill replacing a located anchor). The
        /// capture adds it to its analysis program, so a name the text prints
        /// bare (an enum member, a recursive reference) is found declared
        /// rather than recorded undeclared (#1165). LLM inline text has none.
        #[serde(skip_serializing_if = "Option::is_none")]
        source_file: Option<String>,
        /// carrick#1836: what the text's bare names meant where the inference
        /// printed them, for the names `source_file` cannot resolve. Copied
        /// from the inference the text came from; empty for any other text.
        #[serde(default, skip_serializing_if = "Vec::is_empty")]
        printed_names: Vec<PrintedName>,
        /// carrick#1842: the text is a body its call site reads as raw text.
        /// The capture copies it onto the alias's record, which the check
        /// phase reads from every stored stub.
        #[serde(skip_serializing_if = "std::ops::Not::not")]
        raw_text_read: bool,
        /// carrick#2814: the text is a request body or payload whose handler
        /// works when none is sent. The capture copies it onto the alias's
        /// record, which the check phase reads from every stored stub.
        #[serde(skip_serializing_if = "std::ops::Not::not")]
        absent_body_tolerated: bool,
    },
}

impl CaptureAnchor {
    pub fn alias(&self) -> &str {
        match self {
            CaptureAnchor::Symbol { alias, .. }
            | CaptureAnchor::HandlerReturn { alias, .. }
            | CaptureAnchor::Infer { alias, .. }
            | CaptureAnchor::Literal { alias, .. } => alias,
        }
    }

    /// Repo-relative file the anchor reads from, if it has one.
    pub fn source_file(&self) -> Option<&str> {
        match self {
            CaptureAnchor::Symbol { source_file, .. }
            | CaptureAnchor::HandlerReturn { source_file, .. }
            | CaptureAnchor::Infer { source_file, .. } => Some(source_file),
            CaptureAnchor::Literal { source_file, .. } => source_file.as_deref(),
        }
    }
}

