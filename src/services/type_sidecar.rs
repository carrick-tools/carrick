/// Per-alias capture record (serialization tier + self-check outcome).
#[derive(Debug, Clone, Deserialize)]
pub struct CaptureAliasRecord {
    pub alias: String,
    pub anchor_kind: String,
    #[serde(default)]
    pub symbol_name: Option<String>,
    pub source_file: String,
    pub anchor_origin: String,
    pub serialization: String,
    pub self_check: String,
    #[serde(default)]
    pub self_check_detail: Option<String>,
    #[serde(default)]
    pub capture_failure_reason: Option<String>,
    pub top_type_at_self_check: bool,
    /// Every disqualifying `any`/`unknown` the self-check found at DEPTH
    /// (member / element / index signature / type argument) with no failing
    /// pinned-external explanation, sorted by member path.
    ///
    /// The FIRST entry is what the check phase pre-gates on. The rest exist so
    /// a reader of the published type is told which fields are `any` and why
    /// rather than being handed a bare `any` (carrick#376).
    #[serde(default)]
    pub any_provenance: Vec<TypeProvenance>,
    /// Internal module specifiers that fail to resolve in this alias's closure
    /// (carrick#1165). The emitted tree is missing part of what the alias
    /// refers to, so its printed answer can name types nothing declares.
    /// File-granular: every alias whose closure reaches the failing file.
    #[serde(default)]
    pub dangling_specifiers: Vec<String>,
    /// Identifiers the alias's anonymous print names that resolve to nothing
    /// in the producer's program where the surface declares the alias
    /// (carrick#1165).
    ///
    /// carrick#1377 rewrites every such reference the print reaches to
    /// `unknown` at its own member position, so a current scan fills this only
    /// for what the rewrite could not reach. It is still read, and still
    /// refuses publication, because the check phase also reads PEER artifacts
    /// captured by earlier releases, whose prints still name what nothing
    /// declares.
    #[serde(default)]
    pub undeclared_names: Vec<String>,
    /// Every position at which the alias's type, as the emitted tree states
    /// it, holds the compiler's unresolved-reference placeholder
    /// (carrick#1446): `""` for the alias's own type, member paths otherwise.
    /// The placeholder prints as the name it could not follow, so the text
    /// reads typed where every reader of the tree reads `any`.
    ///
    /// Kept apart from `any_provenance`, which the check phase pre-gates on:
    /// this list moves what the index tells a reader, never a verdict. It
    /// joins the manifest entry beside the entry's other provenance.
    #[serde(default)]
    pub unresolved_in_tree: Vec<TypeProvenance>,
}

impl CaptureAliasRecord {
    /// Why this alias's printed answer is not a type to publish, if it is not
    /// (carrick#1165): it names something the capture recorded as unresolved,
    /// or it is itself a top type with no pinned external to heal it. A top
    /// type the check phase heals by installing a pin (`allowlisted_external`)
    /// is still worth publishing by name.
    pub fn unpublishable_reason(&self) -> Option<&'static str> {
        if !self.undeclared_names.is_empty() {
            Some("the printed answer names an identifier nothing declares")
        } else if !self.dangling_specifiers.is_empty() {
            Some("the declaration behind the answer imports a module that did not resolve")
        } else if self.top_type_at_self_check && self.self_check == "decayed_internal" {
            Some("the answer is a top type with no pinned external to explain it")
        } else {
            None
        }
    }
}

/// One `any`/`unknown` finding inside a captured or inferred type, with its
/// position and its cause (carrick#376). Mirrors the sidecar's
/// `TypeProvenance`; the sidecar owns the vocabulary and this side only
/// carries it, so `reason` and `kind` stay `String`.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub struct TypeProvenance {
    /// Member path of the finding: empty for the type's own root, otherwise
    /// `sub`, `items<0>.meta`, `[index]`, `()` for a callable return.
    pub path: String,
    /// `any`, `unknown`, or `budget_exhausted`.
    pub kind: String,
    /// Categorized cause: `declared`, `unresolved_import`, `budget_exhausted`,
    /// `no_payload_evidence`, `machinery_envelope`, `coerced_input`,
    /// `no_success_payload`, `no_request_body`, `projected_value_only`,
    /// `serialised_body_unread`, `body_built_by_callee`, `result_member_missing`,
    /// `not_recorded`.
    pub reason: String,
    /// One scrubbed sentence a reader can act on.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub detail: Option<String>,
}

