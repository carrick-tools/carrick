/// Errors that can occur when using the TypeSidecar
#[derive(Debug, Clone)]
pub enum SidecarError {
    /// Failed to spawn the sidecar process
    SpawnFailed(String),
    /// Sidecar initialization failed
    InitFailed(String),
    /// Sidecar is not ready to handle requests
    NotReady(String),
    /// Operation timed out
    Timeout,
    /// Sidecar process died unexpectedly
    ProcessDied,
    /// I/O error communicating with sidecar
    IoError(String),
    /// Failed to serialize request
    SerializationError(String),
    /// Failed to deserialize response
    DeserializationError(String),
    /// Definition resolution failed
    ResolutionFailed(String),
    /// v2 capture failed
    CaptureFailed(String),
    /// v2 check failed
    CheckFailed(String),
    /// The sidecar could not list or add its program's files
    ProgramFilesFailed(String),
    /// The sidecar answered a position-rows walk with an error (carrick#2405)
    PositionRowsFailed(String),
    /// The sidecar answered an implementations request with an error (carrick#2432)
    ImplementationsFailed(String),
    /// This process was signalled while the wait was on (carrick#1387).
    Interrupted(crate::shutdown::Interrupted),
}

impl SidecarError {
    /// Whether this failure is environmental — the machine or this run having
    /// a bad day — rather than a repeatable property of the checkout.
    ///
    /// A missed deadline, a dead process or a broken pipe say nothing about
    /// the code being scanned and will not reproduce on the next run, so a
    /// scan may treat them as reasons to stop. An initialization error (the
    /// sidecar answered, with a complaint about a tsconfig) or a sidecar that
    /// is not installed reproduce every time, and stopping on those would
    /// make a repo permanently red.
    pub fn is_environmental(&self) -> bool {
        matches!(
            self,
            SidecarError::Timeout | SidecarError::ProcessDied | SidecarError::IoError(_)
        )
    }

    /// Whether the sidecar process was gone when this was asked of it: its
    /// stdout closed before the answer came, or the request could not be
    /// written to its stdin. A frame the process was still writing when it
    /// ended reads as the first of these (see [`SidecarProcess::spawn`]).
    pub fn is_process_death(&self) -> bool {
        matches!(self, SidecarError::ProcessDied | SidecarError::IoError(_))
    }

    /// Whether, after an operation failed this way, there is no process left
    /// to ask: the next request would fail the same way, so a caller with
    /// more to send counts it as unsent instead (the signature pass), and a
    /// pool hands it to another process ([`SidecarPool::run`]).
    ///
    /// A timed-out operation has already had its process replaced by a fresh
    /// one (carrick#1914), a frame that could not be written or read says
    /// nothing about the process, and a failed resolution, capture or check
    /// is the process's own answer. The rest say the process is gone or its
    /// replacement never came up.
    ///
    /// [`SidecarPool::run`]: crate::services::sidecar_pool::SidecarPool::run
    pub fn leaves_no_process(&self) -> bool {
        match self {
            SidecarError::Timeout
            | SidecarError::SerializationError(_)
            | SidecarError::DeserializationError(_)
            | SidecarError::ResolutionFailed(_)
            | SidecarError::CaptureFailed(_)
            | SidecarError::CheckFailed(_)
            | SidecarError::ProgramFilesFailed(_)
            | SidecarError::PositionRowsFailed(_)
            | SidecarError::ImplementationsFailed(_) => false,
            SidecarError::SpawnFailed(_)
            | SidecarError::InitFailed(_)
            | SidecarError::NotReady(_)
            | SidecarError::ProcessDied
            | SidecarError::IoError(_)
            | SidecarError::Interrupted(_) => true,
        }
    }
}

impl std::fmt::Display for SidecarError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            SidecarError::SpawnFailed(e) => write!(f, "Failed to spawn sidecar: {}", e),
            SidecarError::InitFailed(e) => write!(f, "Sidecar initialization failed: {}", e),
            SidecarError::NotReady(e) => write!(f, "Sidecar not ready: {}", e),
            SidecarError::Timeout => write!(f, "Sidecar operation timed out"),
            SidecarError::ProcessDied => write!(f, "Sidecar process died unexpectedly"),
            SidecarError::IoError(e) => write!(f, "I/O error: {}", e),
            SidecarError::SerializationError(e) => write!(f, "Serialization error: {}", e),
            SidecarError::DeserializationError(e) => write!(f, "Deserialization error: {}", e),
            SidecarError::ResolutionFailed(e) => write!(f, "Definition resolution failed: {}", e),
            SidecarError::CaptureFailed(e) => write!(f, "v2 capture failed: {}", e),
            SidecarError::CheckFailed(e) => write!(f, "v2 check failed: {}", e),
            SidecarError::ProgramFilesFailed(e) => write!(f, "Program files request failed: {}", e),
            SidecarError::PositionRowsFailed(e) => write!(f, "Position rows walk failed: {}", e),
            SidecarError::ImplementationsFailed(e) => {
                write!(f, "Implementations request failed: {}", e)
            }
            SidecarError::Interrupted(e) => write!(f, "{e}"),
        }
    }
}

impl std::error::Error for SidecarError {}

