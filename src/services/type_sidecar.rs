/// Env override for the sidecar's V8 old-space cap, in MB. `0` (or an
/// unparseable value) means "do not pass the flag at all" — V8's own default.
pub const MAX_OLD_SPACE_ENV: &str = "CARRICK_SIDECAR_MAX_OLD_SPACE_MB";

/// Floor for the derived cap. Below this the sidecar cannot hold a
/// mid-sized program's type graph, so a machine this small is better served
/// failing loudly than being handed a cap that is worse than the default.
const MIN_OLD_SPACE_MB: u64 = 2048;

/// Ceiling for the derived cap. The sidecar is one of several processes in a
/// scan (the Rust scanner, and `check_v2`'s spawned installer/compiler), so
/// it never claims the whole machine.
const MAX_OLD_SPACE_MB: u64 = 8192;

/// Fraction of physical memory the sidecar's heap may claim.
const OLD_SPACE_FRACTION_NUMERATOR: u64 = 3;
const OLD_SPACE_FRACTION_DENOMINATOR: u64 = 4;

/// The V8 old-space cap to hand the sidecar, in MB, given the machine's
/// physical memory.
///
/// V8's default cap is a function of the host, not of the program being
/// analysed: on a 64-bit machine it lands near 4 GB regardless of how large
/// the TypeScript program is. A ~3k-file program exhausts it while the
/// checker materialises types and the process dies with
/// `FATAL ERROR: Ineffective mark-compacts near heap limit` (carrick#535),
/// after which the scan continues with no types at all.
///
/// Deriving the cap from physical memory rather than hardcoding one keeps a
/// small CI runner honest: letting V8 grow past the pages the machine can
/// back trades a JS heap error for an OS OOM kill, which is a worse failure
/// because it carries no diagnostic. `None` (memory unknown) falls back to
/// the floor.
fn old_space_cap_mb(total_memory_mb: Option<u64>) -> u64 {
    let derived = total_memory_mb
        .map(|total| total * OLD_SPACE_FRACTION_NUMERATOR / OLD_SPACE_FRACTION_DENOMINATOR)
        .unwrap_or(MIN_OLD_SPACE_MB);
    derived.clamp(MIN_OLD_SPACE_MB, MAX_OLD_SPACE_MB)
}

/// The cgroup memory limit in MB, when this process runs under one.
///
/// `/proc/meminfo` reports the HOST's memory, so a scanner inside a
/// memory-limited container would otherwise derive a cap from memory it
/// cannot touch and be OS-killed at the limit — exactly the silent failure
/// the sizing exists to avoid. cgroup v2 first, then v1. `max` (v2) and v1's
/// "no limit" sentinel both read as no limit.
#[cfg(target_os = "linux")]
fn cgroup_memory_limit_mb() -> Option<u64> {
    const V2: &str = "/sys/fs/cgroup/memory.max";
    const V1: &str = "/sys/fs/cgroup/memory/memory.limit_in_bytes";
    for path in [V2, V1] {
        let Ok(raw) = std::fs::read_to_string(path) else {
            continue;
        };
        let trimmed = raw.trim();
        if trimmed == "max" {
            continue;
        }
        let Ok(bytes) = trimmed.parse::<u64>() else {
            continue;
        };
        // v1 writes a near-u64::MAX sentinel when unlimited. Anything past a
        // terabyte is that sentinel, not a real container limit.
        let mb = bytes / (1024 * 1024);
        if mb == 0 || mb > 1024 * 1024 {
            continue;
        }
        return Some(mb);
    }
    None
}

/// How many processes the kernel has killed for memory in this process's
/// cgroup, when it runs under one that says (carrick#2208).
///
/// cgroup v2 `memory.events`, then v1 `memory.oom_control`; both carry an
/// `oom_kill <n>` line. Linux only: anywhere else there is no counter, and a
/// SIGKILL stays unclassified.
#[cfg(target_os = "linux")]
pub(crate) fn cgroup_oom_kills() -> Option<u64> {
    const V2: &str = "/sys/fs/cgroup/memory.events";
    const V1: &str = "/sys/fs/cgroup/memory/memory.oom_control";
    [V2, V1]
        .into_iter()
        .find_map(|path| oom_kill_count(&std::fs::read_to_string(path).ok()?))
}

#[cfg(not(target_os = "linux"))]
pub(crate) fn cgroup_oom_kills() -> Option<u64> {
    None
}

/// The `oom_kill` count in a cgroup memory file's text. The key is matched
/// whole: v1's file also carries `oom_kill_disable`.
fn oom_kill_count(text: &str) -> Option<u64> {
    text.lines().find_map(|line| {
        let mut fields = line.split_whitespace();
        (fields.next()? == "oom_kill").then(|| fields.next()?.parse().ok())?
    })
}

/// Whether the cgroup's OOM-kill counter rose between two reads. Unknown
/// either side reads as no.
pub(crate) fn oom_kills_rose(before: Option<u64>, after: Option<u64>) -> bool {
    matches!((before, after), (Some(before), Some(after)) if after > before)
}

/// The tail V8 prints on every fatal heap-exhaustion line.
const HEAP_OUT_OF_MEMORY: &str = "JavaScript heap out of memory";

/// V8's hard size limits print the same tail, and a larger heap does not lift
/// them, so they are not memory deaths.
const HARD_SIZE_LIMITS: [&str; 3] = [
    "invalid table size",
    "invalid array length",
    "Invalid array buffer length",
];

/// Whether one stderr line is V8's fatal heap-exhaustion line (`Reached heap
/// limit`, `Ineffective mark-compacts near heap limit`, and the other forms
/// all end in `JavaScript heap out of memory`), and not one of the hard size
/// limits that end the same way.
///
/// The same rule as the sidecar's `carriesHeapLimitLine` (check.ts) applies
/// to its compiler's stderr; both are tested against one table,
/// `src/sidecar/test/fixtures/heap-limit-lines.json`.
pub(crate) fn is_heap_limit_line(line: &str) -> bool {
    line.contains(HEAP_OUT_OF_MEMORY) && !HARD_SIZE_LIMITS.iter().any(|limit| line.contains(limit))
}

/// A type-checker process that died of memory, and how (carrick#2208).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MemoryDeath {
    /// It aborted with V8's heap-exhaustion line on stderr: the heap cap it
    /// was given was not enough.
    HeapLimit,
    /// It was killed (SIGKILL) and the cgroup's OOM-kill counter rose while
    /// it ran: the machine's memory was not enough.
    OomKilled,
}

impl MemoryDeath {
    /// How a process that ended `end` died, when it was memory.
    ///
    /// The rule leans wide on purpose: a false positive costs one retry on a
    /// larger machine, and a false negative ships a typeless index.
    /// - An abort (SIGABRT, or exit code 134 when a shell sat between) is a
    ///   heap death only with V8's line on stderr (`heap_line`); without it
    ///   the process merely aborted.
    /// - A SIGKILL is an OOM kill only when the cgroup counted one
    ///   (`oom_kills_rose`); otherwise something else killed it.
    pub fn classify(
        end: Option<ProcessEnd>,
        heap_line: bool,
        oom_kills_rose: bool,
    ) -> Option<Self> {
        match end? {
            ProcessEnd::Signal(ProcessEnd::SIGABRT) | ProcessEnd::Code(134) if heap_line => {
                Some(MemoryDeath::HeapLimit)
            }
            ProcessEnd::Signal(ProcessEnd::SIGKILL) if oom_kills_rose => {
                Some(MemoryDeath::OomKilled)
            }
            _ => None,
        }
    }

    /// The kind, as a stable token.
    pub fn as_str(self) -> &'static str {
        match self {
            MemoryDeath::HeapLimit => "heap_limit",
            MemoryDeath::OomKilled => "oom_killed",
        }
    }
}

/// Physical memory in MB, or `None` when this platform's probe fails.
///
/// Deliberately dependency-free: one `/proc/meminfo` read on Linux (where CI
/// runs) and one `sysctl` call on macOS (where it is developed). On Linux the
/// cgroup limit wins when it is lower, because that is the memory this
/// process actually has.
fn total_memory_mb() -> Option<u64> {
    #[cfg(target_os = "linux")]
    {
        let meminfo = std::fs::read_to_string("/proc/meminfo").ok()?;
        let kb: u64 = meminfo
            .lines()
            .find_map(|line| line.strip_prefix("MemTotal:"))?
            .split_whitespace()
            .next()?
            .parse()
            .ok()?;
        let host_mb = kb / 1024;
        return Some(match cgroup_memory_limit_mb() {
            Some(limit) => host_mb.min(limit),
            None => host_mb,
        });
    }
    #[cfg(target_os = "macos")]
    {
        let out = Command::new("sysctl")
            .args(["-n", "hw.memsize"])
            .output()
            .ok()?;
        let bytes: u64 = String::from_utf8(out.stdout).ok()?.trim().parse().ok()?;
        return Some(bytes / (1024 * 1024));
    }
    #[allow(unreachable_code)]
    None
}

/// The V8 old-space cap every sidecar process of this run is started with,
/// in MB, or `None` when the override disables it and V8's own default
/// applies.
pub fn heap_cap_mb() -> Option<u64> {
    match std::env::var(MAX_OLD_SPACE_ENV) {
        Ok(raw) => match raw.trim().parse::<u64>() {
            Ok(0) | Err(_) => None,
            Ok(mb) => Some(mb),
        },
        Err(_) => Some(old_space_cap_mb(total_memory_mb())),
    }
}

/// The `--max-old-space-size` argument for this run, or `None` when the
/// override disables it.
fn max_old_space_arg() -> Option<String> {
    heap_cap_mb().map(|mb| format!("--max-old-space-size={}", mb))
}

/// The sidecar's entry script, found in the known locations: the scan that
/// spawns it and the `check` that starts the resident type daemon from it
/// (carrick#2884) must find the same one, or their build ids differ.
pub fn discover_sidecar_path() -> Option<PathBuf> {
    // The sidecar entry point after building (TypeScript compiles to dist/src/)
    let sidecar_entry = "dist/src/index.js";

    // List of locations to check, in order of priority
    let mut candidates: Vec<PathBuf> = vec![];

    // 0. Told where it is. The npm package (carrick#710) is the case that
    //    needs this: the binary ships in a per-platform package and the
    //    sidecar ships in the main one, beside the `node_modules/` its
    //    dependencies resolve through, so nothing relative to the executable
    //    can reach it.
    if let Ok(configured) = std::env::var("CARRICK_SIDECAR_DIR")
        && !configured.trim().is_empty()
    {
        candidates.push(PathBuf::from(configured));
    }

    candidates.extend([
        // 1. Relative to executable (for packaged distribution)
        executable_relative_path("sidecar"),
        executable_relative_path("../sidecar"),
        executable_relative_path("../lib/sidecar"),
    ]);

    // 2. For development builds, use CARGO_MANIFEST_DIR (set at compile time)
    //    This ensures we find the sidecar regardless of the current working directory
    if let Some(manifest_dir) = option_env!("CARGO_MANIFEST_DIR") {
        candidates.push(PathBuf::from(manifest_dir).join("src/sidecar"));
    }

    // 3. Fallback to relative paths (in case running from project root)
    candidates.extend([
        PathBuf::from("src/sidecar"),
        PathBuf::from("./src/sidecar"),
        PathBuf::from("sidecar"),
    ]);

    for candidate in candidates {
        let full_path = candidate.join(sidecar_entry);
        if full_path.exists() {
            debug!("Checking sidecar candidate: {:?}", full_path);
            return Some(full_path);
        }
    }

    None
}

/// A path relative to the executable's directory.
fn executable_relative_path(relative: &str) -> PathBuf {
    if let Ok(exe_path) = std::env::current_exe()
        && let Some(exe_dir) = exe_path.parent()
    {
        return exe_dir.join(relative);
    }
    PathBuf::from(relative)
}

