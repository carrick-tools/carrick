/// One running sidecar process and the two ends of its pipe.
struct SidecarProcess {
    child: Child,
    stdin: ChildStdin,
    /// Lines the process writes to stdout, in order: see
    /// [`TypeSidecar::responses`].
    responses: Receiver<String>,
    /// What is known about how it might die: see [`DeathEvidence`].
    evidence: DeathEvidence,
}

/// What one sidecar process leaves behind to say whether it died of memory
/// (carrick#2208): whether its stderr carried V8's heap-exhaustion line, and
/// the cgroup's OOM-kill count when it was started.
#[derive(Clone)]
struct DeathEvidence {
    stderr: Arc<StderrEvidence>,
    oom_kills_at_spawn: Option<u64>,
}

/// Set by the stderr reader thread.
#[derive(Default)]
struct StderrEvidence {
    heap_line: AtomicBool,
    /// The reader reached EOF: every line the process wrote has been read.
    closed: AtomicBool,
}

impl SidecarProcess {
    /// Start `node <sidecar_path>` with the heap flag for this run and both
    /// reader threads. Returns as soon as the process exists; nothing has
    /// been asked of it yet.
    fn spawn(sidecar_path: &Path) -> Result<Self, SidecarError> {
        debug!("[type_sidecar] Spawning sidecar from: {:?}", sidecar_path);

        // Spawn the Node.js process. V8 flags MUST precede the script path,
        // or node passes them to the script instead of applying them.
        let mut command = Command::new("node");
        if let Some(heap_arg) = max_old_space_arg() {
            debug!("[type_sidecar] Sidecar heap flag: {}", heap_arg);
            command.arg(heap_arg);
        }
        let mut child = command
            .arg(sidecar_path)
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            .stderr(Stdio::piped()) // Capture stderr, pipe through tracing
            .spawn()
            .map_err(|e| SidecarError::SpawnFailed(e.to_string()))?;

        let stdin = child
            .stdin
            .take()
            .ok_or_else(|| SidecarError::SpawnFailed("Failed to get stdin".to_string()))?;

        let stdout = child
            .stdout
            .take()
            .ok_or_else(|| SidecarError::SpawnFailed("Failed to get stdout".to_string()))?;

        // Read stdout on a background thread, one line per message, into a
        // channel. Every reader in this module then waits on the channel with
        // a deadline it can actually honour. Dropping the sender on EOF or a
        // read error is how a dead sidecar surfaces as `ProcessDied` rather
        // than as a wait that never returns.
        //
        // The thread reads whether or not anyone is waiting, so the pipe is
        // never left full. That is what lets a handler that blocks the
        // sidecar's event loop still get a progress frame out: a frame-sized
        // write to a pipe with room in it completes on the spot, and only a
        // write that finds the pipe full has to wait for the event loop.
        //
        // A frame is a whole line. Text with no newline after it at EOF is a
        // frame the process was still writing when it ended, so it is not
        // passed on: the reader then finds the channel closed and reports
        // the death. Passed on, it parsed as a broken answer, and a sidecar
        // that ran out of heap mid-answer was recorded as a deserialization
        // error at the byte the pipe happened to hold (carrick#1916).
        let responses = frames_of(stdout);

        // Pipe sidecar stderr through tracing on a background thread, keeping
        // whether V8 said its heap ran out: the abort that follows does not
        // say why (carrick#2208).
        let stderr_evidence = Arc::new(StderrEvidence::default());
        if let Some(stderr) = child.stderr.take() {
            let evidence = Arc::clone(&stderr_evidence);
            thread::spawn(move || {
                let reader = BufReader::new(stderr);
                for line in reader.lines().map_while(Result::ok) {
                    if is_heap_limit_line(&line) {
                        evidence.heap_line.store(true, Ordering::SeqCst);
                    }
                    if !line.trim().is_empty() {
                        debug!("{}", line);
                    }
                }
                evidence.closed.store(true, Ordering::SeqCst);
            });
        } else {
            stderr_evidence.closed.store(true, Ordering::SeqCst);
        }

        Ok(Self {
            child,
            stdin,
            responses,
            evidence: DeathEvidence {
                stderr: stderr_evidence,
                oom_kills_at_spawn: cgroup_oom_kills(),
            },
        })
    }
}

/// Read `source` on a thread of its own, one whole line per frame, into a
/// channel: a sidecar process's stdout, or the resident daemon's socket
/// (carrick#2884). The channel disconnects when the source ends, which is how
/// the other end going away surfaces (see [`SidecarProcess::spawn`]).
fn frames_of(source: impl std::io::Read + Send + 'static) -> Receiver<String> {
    let (tx, responses) = channel::<String>();
    thread::spawn(move || {
        let mut reader = BufReader::new(source);
        let mut line = String::new();
        loop {
            line.clear();
            match reader.read_line(&mut line) {
                Ok(0) => break,
                Ok(_) if line.ends_with('\n') => {
                    if tx.send(line.trim_end().to_owned()).is_err() {
                        break; // client gone
                    }
                }
                Ok(cut_off) => {
                    debug!(
                        "[type_sidecar] the sidecar's output ended {} bytes into an unfinished frame",
                        cut_off
                    );
                    break;
                }
                Err(e) => {
                    debug!("[type_sidecar] the sidecar's output ended: {}", e);
                    break;
                }
            }
        }
    });
    responses
}

/// The connection to the resident type daemon a [`TypeSidecar`] answers
/// through instead of a process of its own (carrick#2884).
struct DaemonLink {
    #[cfg(unix)]
    stream: std::os::unix::net::UnixStream,
    /// The daemon's process id, from its answer to `hello`.
    pid: u32,
}

impl DaemonLink {
    /// End this connection, and only it: the daemon serves others.
    fn close(&self) {
        #[cfg(unix)]
        let _ = self.stream.shutdown(std::net::Shutdown::Both);
    }
}

/// A non-terminal frame: the sidecar saying a request is still being worked
/// on. `phase` and `message` are for the log; the frame's arrival is the
/// signal.
#[derive(Debug, Deserialize)]
struct ProgressFrame {
    request_id: String,
    status: String,
    #[serde(default)]
    phase: Option<String>,
    #[serde(default)]
    message: Option<String>,
}

/// The last thing a sidecar said about the request it was working on: the
/// `phase` and `message` of its most recent progress frame.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct OperationProgress {
    pub phase: String,
    pub message: String,
}

/// How a sidecar process that is gone came to an end.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ProcessEnd {
    /// Ended by a signal. Node ends itself with `SIGABRT` when V8 cannot
    /// allocate inside its heap cap; the OS ends a process with `SIGKILL`.
    Signal(i32),
    /// Exited with a code.
    Code(i32),
}

impl ProcessEnd {
    /// The signal a runtime raises on itself to abort.
    pub const SIGABRT: i32 = 6;
    /// The signal the OS ends a process with, the OOM killer included.
    pub const SIGKILL: i32 = 9;

    /// Whether the process aborted itself, which is how Node ends when its
    /// heap is full.
    pub fn is_abort(&self) -> bool {
        *self == ProcessEnd::Signal(Self::SIGABRT)
    }
}

/// `line` as a progress frame, or `None` when it is anything else.
///
/// An answer is read here too, to find out that it is not one: its other
/// fields are skipped rather than built, which costs a scan of the line.
fn progress_frame(line: &str) -> Option<ProgressFrame> {
    serde_json::from_str::<ProgressFrame>(line)
        .ok()
        .filter(|frame| frame.status == "progress")
}

