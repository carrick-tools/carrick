    /// A `verify_library_claims` answer is read from the contract's names
    /// (`verdicts`, `modules`, `duration_ms`), by the same positional rule as
    /// a `verify_client_semantics` one, and never from the HTTP action's
    /// names.
    #[test]
    fn read_library_claims_reads_the_contract_names() {
        let check = |claim_id: &str, receiver: &str| LibraryCheck {
            claim_id: claim_id.into(),
            package: "@fixture/queue".into(),
            export: "default".into(),
            role: LibraryRole::Broker,
            receiver: receiver.into(),
            claim: LibraryClaim::Make {
                form: MakeForm::Call,
                member: None,
                base: None,
                prefix: None,
                name: None,
                handler: None,
                runs: None,
                key_labels: BTreeMap::new(),
                name_scope: None,
                picker: None,
            },
        };
        let checks = [check("a", "export"), check("b", "export")];
        let response =
            |json: serde_json::Value| -> SidecarResponse { serde_json::from_value(json).unwrap() };
        let verdict = |claim_id: &str| serde_json::json!({ "claim_id": claim_id, "receiver": "export", "verdict": "verified" });

        let answer = read_library_claims(
            response(serde_json::json!({
                "request_id": "1", "status": "success",
                "verdicts": [verdict("a"), { "claim_id": "b", "receiver": "export", "verdict": "failed", "reason": "name_ambiguous" }],
                "modules": [{ "package": "@fixture/queue", "installed_version": "2.4.1" }],
                "duration_ms": 41
            })),
            &checks,
        )
        .unwrap();
        assert_eq!(answer.verdicts.len(), 2);
        assert_eq!(answer.verdicts[1].verdict, SemanticsVerdict::Failed);
        assert_eq!(answer.verdicts[1].reason.as_deref(), Some("name_ambiguous"));
        assert_eq!(
            answer.modules[0].installed_version.as_deref(),
            Some("2.4.1")
        );
        assert_eq!(answer.duration_ms, Some(41));

        let old_names = read_library_claims(
            response(serde_json::json!({
                "request_id": "2", "status": "success",
                "semantics": [verdict("a"), verdict("b")]
            })),
            &checks,
        );
        assert!(
            matches!(old_names, Err(SidecarError::CheckFailed(m)) if m == "verify_library_claims answered 0 of 2 checks")
        );

        let swapped = read_library_claims(
            response(serde_json::json!({
                "request_id": "3", "status": "success",
                "verdicts": [verdict("b"), verdict("a")]
            })),
            &checks,
        );
        assert!(
            matches!(swapped, Err(SidecarError::CheckFailed(m)) if m.contains("verify_library_claims answered b @ export where a @ export"))
        );

        let refused = read_library_claims(
            response(serde_json::json!({
                "request_id": "4", "status": "error", "errors": ["Invalid request: checks.0.claim"]
            })),
            &checks,
        );
        assert!(
            matches!(refused, Err(SidecarError::CheckFailed(m)) if m == "Invalid request: checks.0.claim")
        );
    }

    /// carrick#1985: an infer answer's timing is for the log. One this reader
    /// knows is read; one it does not know is no timing, and the types that
    /// came with it are still the answer.
    #[test]
    fn an_infer_timing_the_reader_does_not_know_costs_the_log_and_not_the_types() {
        let answer = |timing: serde_json::Value| -> SidecarResponse {
            serde_json::from_value(serde_json::json!({
                "request_id": "req-9",
                "status": "success",
                "inferred_types": [{
                    "alias": "__sig0",
                    "type_string": "Promise<void>",
                    "is_explicit": false,
                    "source_location": { "file_path": "/r/a.ts", "start_line": 3, "end_line": 5 },
                    "infer_kind": "signature_return"
                }],
                "infer_timing": timing,
            }))
            .expect("the frame parses whatever its timing holds")
        };
        let slot = serde_json::json!({
            "alias": "__sig0", "file_path": "/r/a.ts", "line_number": 3,
            "infer_kind": "signature_return", "ms": 9470.1, "type_ms": 9468.8,
            "print_ms": 0.1, "printed_length": 13, "first_in_file": true
        });

        let known = answer(serde_json::json!({
            "slots": 1, "slots_ms": 9470.1, "type_ms": 9468.8, "print_ms": 0.1,
            "first_in_file_slots": 1, "first_in_file_ms": 9470.1,
            "slowest": [slot.clone()], "longest_printed": slot.clone()
        }));
        let timing = known
            .infer_timing
            .expect("a timing in the known shape is read");
        assert_eq!(timing.slots, 1);
        assert_eq!(timing.type_ms, 9468.8);
        assert_eq!(timing.slowest[0].alias.as_deref(), Some("__sig0"));
        assert_eq!(timing.slowest[0].infer_kind, InferKind::SignatureReturn);
        assert_eq!(timing.slowest[0].printed_length, 13);
        assert_eq!(timing.longest_printed, Some(timing.slowest[0].clone()));

        // A member renamed, a member missing, another type altogether, null.
        for unknown in [
            serde_json::json!({ "slots": 1, "total_ms": 9470.1, "slowest": [slot.clone()] }),
            serde_json::json!({ "slots": "one" }),
            serde_json::json!("9470ms"),
            serde_json::Value::Null,
        ] {
            let parsed = answer(unknown.clone());
            assert_eq!(parsed.infer_timing, None, "{unknown}");
            assert_eq!(
                parsed.inferred_types.as_ref().map(Vec::len),
                Some(1),
                "the types are kept: {unknown}"
            );
        }

        // No timing at all: an answer from a sidecar that sends none.
        let silent: SidecarResponse = serde_json::from_value(serde_json::json!({
            "request_id": "req-9", "status": "success", "inferred_types": []
        }))
        .unwrap();
        assert_eq!(silent.infer_timing, None);
    }

