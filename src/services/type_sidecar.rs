/// Four-bucket verdict classifier output (pinned decision 7), plus the
/// bucket the retype check files when a producer's published type is wider
/// than what its handler returns (carrick#1516). That last one never leaves
/// the scanner as a value: on the wire it is a `compatible` verdict with
/// `producer_wider: true` beside it.
#[derive(Debug, Clone, Copy, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum VerdictBucket {
    Compatible,
    Incompatible,
    Unverifiable,
    GateCaughtBakedAny,
    /// The published type does not fit the consumer and the handler's
    /// unwidened return does: its own class, never a break.
    ProducerWider,
}

/// One structured verdict from `check_v2`, keyed by pair identity.
#[derive(Debug, Clone, Deserialize)]
pub struct CheckVerdict {
    /// Deterministic FNV-1a hash of the pair (never a temp path).
    pub pair_id: String,
    /// Caller key, echoed for the verdict join.
    pub pair_key: String,
    pub bucket: VerdictBucket,
    /// For gate/import buckets: which side and which gate fired.
    #[serde(default)]
    pub gate: Option<String>,
    /// Scrubbed user-facing message (never absolute paths / scan internals).
    #[serde(default)]
    pub diagnostic: Option<String>,
    /// TS diagnostic codes attributed to this pair's probe, sorted.
    #[serde(default)]
    pub codes: Vec<i64>,
    /// Whether this verdict is a FACT about two known types (carrick#707,
    /// R1d): the bucket is `compatible` or `incompatible` AND a deep walk over
    /// both sides, run after the pinned externals installed, found no
    /// `any`/`unknown` at any depth. Every other outcome is `false`.
    ///
    /// `bucket` alone cannot say this: a side carrying `any` three members
    /// down clears every whole-type probe gate and then reads compatible
    /// against any counterparty at all.
    #[serde(default)]
    pub resolved: bool,
    /// Why `resolved` is false. Absent exactly when it is true.
    #[serde(default)]
    pub unresolved_reason: Option<String>,
    /// Which side's type left the verdict unresolved, when one side did
    /// (carrick#1491). The retype check reads this to find the pairs whose
    /// CONSUMER call it can judge, instead of parsing `unresolved_reason`.
    #[serde(default)]
    pub unresolved_side: Option<VerdictSide>,
    /// Statements about this comparison that are neither the verdict nor an
    /// unresolution (carrick#1341): an optionality gap that is legal and still
    /// a drift, and the note that the comparison was made against the JSON
    /// wire form. Written on every bucket, empty when there is nothing to add.
    ///
    /// `#[serde(default)]` so a check result from a sidecar build that
    /// predates the field reads as no notes rather than failing the whole
    /// check — the same terms every other additive field here is read on.
    #[serde(default)]
    pub notes: Vec<String>,
}

